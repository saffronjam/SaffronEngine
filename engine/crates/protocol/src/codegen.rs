/// One DTO type's `ts-rs` declaration: `(ident, decl)` where `decl` is the raw `type X = ...;`
/// string `ts-rs` emits — an object type for structs, a string-literal union for enums, the
/// `string` alias for [`Uuid`]. `ident` is the Rust type name.
#[must_use]
pub fn ts_decls() -> Vec<(&'static str, String)> {
    macro_rules! decls {
        ($($t:ty),+ $(,)?) => {
            vec![$((stringify!($t), <$t as TS>::decl())),+]
        };
    }
    dto_universe!(decls)
}

/// Every named OpenRPC schema fragment, in the same order.
#[must_use]
pub fn schema_fragments() -> Vec<(&'static str, Value)> {
    macro_rules! frags {
        ($($t:ty),+ $(,)?) => {
            vec![$((stringify!($t), fragment_for::<$t>(stringify!($t)))),+]
        };
    }
    dto_universe!(frags)
}

#[cfg(test)]
mod tests {
    use std::collections::{BTreeSet, HashMap};

    use super::*;

    /// The tag key of a serde-tagged union, read off the `schemars` fragment: every `oneOf` branch
    /// is an object requiring the same property, whose schema is a string `const`. An externally
    /// tagged or untagged union has no such property and yields `None`.
    fn tagged_union_key(fragment: &Value) -> Option<String> {
        let branches = fragment.get("oneOf")?.as_array()?;
        let mut common: Option<BTreeSet<String>> = None;
        for branch in branches {
            let required: BTreeSet<&str> = branch
                .get("required")?
                .as_array()?
                .iter()
                .filter_map(Value::as_str)
                .collect();
            let consts: BTreeSet<String> = branch
                .get("properties")?
                .as_object()?
                .iter()
                .filter(|(name, schema)| {
                    required.contains(name.as_str()) && schema.get("const").is_some()
                })
                .map(|(name, _)| name.clone())
                .collect();
            common = Some(match common {
                None => consts,
                Some(prev) => prev.intersection(&consts).cloned().collect(),
            });
        }
        common?.into_iter().next()
    }

    #[test]
    fn uuid_decl_is_the_string_alias() {
        let decls = ts_decls();
        let (_, decl) = decls.iter().find(|(n, _)| *n == "Uuid").unwrap();
        assert_eq!(decl, "type Uuid = string;");
    }

    /// `ts-rs` reads `#[serde(tag = "…")]` only while the rest of that attribute is a form it
    /// understands: adding `deny_unknown_fields` makes it drop the tag and emit an externally
    /// tagged union that no engine reply ever matches. Every tagged DTO therefore mirrors the tag
    /// and renames into an explicit `#[ts(…)]`, and this holds the two generators to one shape.
    #[test]
    fn every_tagged_union_carries_its_tag_in_typescript() {
        let decls: HashMap<&str, String> = ts_decls().into_iter().collect();
        let untagged: Vec<String> = schema_fragments()
            .iter()
            .filter_map(|(name, fragment)| {
                let tag = tagged_union_key(fragment)?;
                let decl = decls.get(name).expect("every DTO emits a declaration");
                (!decl.contains(&format!("\"{tag}\":"))).then(|| format!("{name} (tag `{tag}`)"))
            })
            .collect();
        assert!(
            untagged.is_empty(),
            "these DTOs are tagged on the wire but not in TypeScript — mirror the serde tag and \
             renames into #[ts(…)]: {}",
            untagged.join(", ")
        );
    }
}
