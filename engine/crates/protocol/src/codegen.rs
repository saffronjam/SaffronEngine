//! The protocol codegen surface the `xtask gen-protocol` emitters read.
//!
//! Rust has no runtime reflection, so the emitters cannot enumerate the DTO set themselves. One
//! ordered universe of named DTOs lives here and drives both outputs: every type's `ts-rs`
//! declaration and every type's `schemars` OpenRPC fragment. A dropped or added type fails to
//! compile here, so the two outputs cannot drift apart.

